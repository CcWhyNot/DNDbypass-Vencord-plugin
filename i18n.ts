function getLocale(): Locale {
    const raw = LocaleStore?.locale ?? "en";
    const base = raw.split("-")[0].toLowerCase() as Locale;
    return SUPPORTED_LOCALES.includes(base) ? base : "en";
}

export function t(key: keyof typeof translations["en"], vars?: Record<string, string>): string {
    const locale = getLocale();
    const template = translations[locale][key] ?? translations.en[key] ?? key;

    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (match, varName) => vars[varName] ?? match);
}
